import 'dart:io';

import 'package:path/path.dart' as p;

import 'nix/config/nix_config.dart';

/// Generator for Clan files using the `nix` library.
///
/// Generates into `<projectRoot>/clan/`:
/// - `nix.yaml`      — Nix build config (from the nix library schema)
/// - `flake.nix`     — Nix flake
/// - `clan.yaml`     — main clan configuration
/// - `users.yaml`    — user accounts
/// - `perms.yaml`    — permissions/roles
/// - `nodes.yaml`    — machine nodes
/// - `services.yaml` — services
class ClanGenerator {
  final String projectRoot;

  ClanGenerator({String? projectRoot})
      : projectRoot = projectRoot ?? Directory.current.path;

  /// نقطة الدخول: توليد كل ملفات Clan
  Future<void> generate([String? root]) async {
    final base = root ?? projectRoot;
    final projectDir = Directory(base);
    if (!projectDir.existsSync()) {
      throw FileSystemException('Project root not found', base);
    }

    final clanDir = Directory(p.join(base, 'clan'));
    if (!clanDir.existsSync()) {
      clanDir.createSync(recursive: true);
    }

    await _write(clanDir, 'nix.yaml', _nixYamlContent());
    await _write(clanDir, 'flake.nix', _flakeNixContent());
    await _write(clanDir, 'clan.yaml', _clanYamlContent());
    await _write(clanDir, 'users.yaml', _usersYamlContent());
    await _write(clanDir, 'perms.yaml', _permsYamlContent());
    await _write(clanDir, 'nodes.yaml', _nodesYamlContent());
    await _write(clanDir, 'services.yaml', _servicesYamlContent());

    stdout.writeln('✓ Clan files generated in ${clanDir.path}');
  }

  Future<void> _write(Directory dir, String name, String content) async {
    final file = File(p.join(dir.path, name));
    await file.writeAsString(content);
  }

  /// Build a [NixConfig] from the nix library schema (used for validation/audit).
  NixConfig buildNixConfig() => NixConfig(
        projectName: 'fastfree_clan',
        flutter: const FlutterConfig(version: '3.38.2', channel: 'stable'),
        flakePath: 'nix',
        platforms: {
          'linux': const PlatformConfig(
            name: 'linux',
            shell: 'linux',
            buildCommand: 'flutter build linux --release',
            buildOutput: 'build/linux/x64/release/bundle/',
          ),
        },
      );

  String _nixYamlContent() {
    final config = buildNixConfig();
    final buffer = StringBuffer()
      ..writeln('# nix.yaml: Nix reproducible build config (auto-generated)')
      ..writeln('# Schema: package:nix (https://pub.dev/packages/nix)')
      ..writeln('project:')
      ..writeln('  name: ${config.projectName}')
      ..writeln()
      ..writeln('flutter:')
      ..writeln('  version: "${config.flutter.version}"')
      ..writeln('  channel: ${config.flutter.channel}')
      ..writeln()
      ..writeln('nix:')
      ..writeln('  flake: ${config.flakePath}')
      ..writeln()
      ..writeln('platforms:');
    for (final platform in config.platforms.values) {
      buffer
        ..writeln('  ${platform.name}:')
        ..writeln('    shell: ${platform.shell}')
        ..writeln('    build:')
        ..writeln('      command: ${platform.buildCommand}')
        ..writeln('      output: ${platform.buildOutput}');
    }
    return buffer.toString();
  }

  String _flakeNixContent() => '''
{
  description = "fastfree_clan";

  inputs = {
    nixpkgs.url = "github:NixOS/nixpkgs/nixos-unstable";
    flake-utils.url = "github:numtide/flake-utils";
  };

  outputs = { self, nixpkgs, flake-utils }:
    flake-utils.lib.eachDefaultSystem (system: {
      devShells.default = nixpkgs.legacyPackages.\${system}.mkShell {
    buildInputs = [ ];
  };
    });
}
''';

  String _clanYamlContent() => '''
# Clan configuration — auto-generated by fastfree_clan
project:
  name: fastfree_clan
  version: 1.0.0
  description: "FastFree ERP Clan module"

clan:
  name: fastfree_clan
  cluster_id: default
  leader: admin
  description: "Clan for FastFree ERP"

roles:
  admin:
    - clan:read
    - clan:write
    - clan:admin
  user:
    - clan:read

nodes:
  - name: localhost
    type: local
    roles: [admin]

services:
  - name: api
    port: 8080
    type: http
''';

  String _usersYamlContent() => '''
# Users — auto-generated by fastfree_clan
users:
  - name: admin
    role: admin
    email: admin@fastfree.local
    active: true
  - name: user
    role: user
    email: user@fastfree.local
    active: true
''';

  String _permsYamlContent() => '''
# Permissions — auto-generated by fastfree_clan
permissions:
  clan: [read, write, admin]
  users: [read, write, delete]
  services: [read, start, stop]
''';

  String _nodesYamlContent() => '''
# Nodes — auto-generated by fastfree_clan
nodes:
  - name: localhost
    type: local
    host: 127.0.0.1
    roles: [admin]
    services: [api]
''';

  String _servicesYamlContent() => '''
# Services — auto-generated by fastfree_clan
services:
  - name: api
    port: 8080
    type: http
    config:
      host: 0.0.0.0
      environment: production
''';

  /// فحص صحة الملفات المولّدة
  Future<Map<String, dynamic>> audit([String? root]) async {
    final base = root ?? projectRoot;
    final clanDir = Directory(p.join(base, 'clan'));
    const files = [
      'nix.yaml',
      'flake.nix',
      'clan.yaml',
      'users.yaml',
      'perms.yaml',
      'nodes.yaml',
      'services.yaml',
    ];

    final results = <String, dynamic>{};
    for (final name in files) {
      final file = File(p.join(clanDir.path, name));
      final exists = file.existsSync();
      results[name] = {
        'exists': exists,
        'size': exists ? file.lengthSync() : 0,
        'valid': exists && file.lengthSync() > 0,
      };
    }
    return results;
  }

  /// قائمة ملفات Clan الموجودة
  List<String> listFiles([String? root]) {
    final base = root ?? projectRoot;
    final clanDir = Directory(p.join(base, 'clan'));
    if (!clanDir.existsSync()) return const [];
    return clanDir
        .listSync()
        .whereType<File>()
        .map((f) => p.basename(f.path))
        .toList();
  }
}
