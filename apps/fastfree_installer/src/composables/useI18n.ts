const LOCALE_STORAGE_KEY = 'fastfree_installer_locale';

export const currentLocale = ref<Locale>('en');

export const isRtl = computed(() => currentLocale.value === 'ar');

export function setLocale(lang: Locale) {
  currentLocale.value = lang;
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, lang);
    } catch {
      // Ignore storage errors in restricted contexts
    }
  }
}

export function toggleLocale() {
  setLocale(currentLocale.value === 'ar' ? 'en' : 'ar');
}

/**
 * Nested key path translation helper
 * Usage: t('discovery.title') or t('discovery.logicalCores', { count: 8 })
 */
export function t(path: string, params?: Record<string, string | number>): string {
  const keys = path.split('.');
  let current: any = messages[currentLocale.value];

  for (const k of keys) {
    if (current && typeof current === 'object' && k in current) {
      current = current[k];
    } else {
      // Fallback to English
      let fallback: any = messages.en;
      for (const fbKey of keys) {
        if (fallback && typeof fallback === 'object' && fbKey in fallback) {
          fallback = fallback[fbKey];
        } else {
          return path;
        }
      }
      current = fallback;
      break;
    }
  }

  if (typeof current !== 'string') {
    return path;
  }

  if (params) {
    return current.replace(/\{(\w+)\}/g, (_, match) => {
      return match in params ? String(params[match]) : `{${match}}`;
    });
  }

  return current;
}

export function useI18n() {
  return {
    locale: currentLocale,
    isRtl,
    setLocale,
    toggleLocale,
    t,
  };
}
