/** Default lang for first install; explicit settings value wins. */
export function resolveBoardLang(settingsValue?: { locale?: string }): BoardLang {
  return settingsValue?.locale === "en" ? "en" : "ar"
}

export function isRtl(lang: BoardLang): boolean {
  return lang === "ar"
}

export function boardTranslate(lang: BoardLang, key: string, params?: Record<string, string | number>): string {
  let out = boardCatalog[lang][key] ?? boardCatalog.en[key] ?? key
  if (!params) return out
  for (const [name, value] of Object.entries(params)) out = out.split(`{{${name}}}`).join(String(value))
  return out
}

export function boardPlural(lang: BoardLang, key: string, count: number): string {
  const en = boardCatalog[lang]
  const pick =
    count === 0 ? `${key}.zero`
    : count === 1 ? `${key}.one`
    : count === 2 ? `${key}.two`
    : count < 11 ? `${key}.few`
    : `${key}.many`
  const template = en[pick] ?? en[`${key}.other`] ?? key
  return template.split("{{count}}").join(String(count))
}


